using System.Data.Common;
using Microsoft.Data.Sqlite;
using Npgsql;

namespace Packory;

/// <summary>
/// Authoritative, additive skill-release state. Stored in the selected metadata database;
/// never infer authorization from the presence of an artifact in the blob store.
/// </summary>
public sealed class SkillSecurityStore(Settings settings)
{
    public sealed record Revision(
        string Name, string Version, string Description, string Sha256, string StagingKey,
        string State, int? RiskScore, string? Recommendation, string? ReportJson, string UpdatedAt);

    private DbConnection Open()
    {
        DbConnection connection;
        if (settings.MetadataProvider == "postgresql")
            connection = new NpgsqlConnection(settings.PostgresConnectionString);
        else
        {
            Directory.CreateDirectory(settings.DataDirectory);
            connection = new SqliteConnection(new SqliteConnectionStringBuilder
            {
                DataSource = Path.Combine(Path.GetFullPath(settings.DataDirectory), "packory.sqlite"),
                Mode = SqliteOpenMode.ReadWriteCreate,
                Cache = SqliteCacheMode.Shared
            }.ToString());
        }
        connection.Open();
        if (connection is SqliteConnection sqlite)
        {
            using var pragma = sqlite.CreateCommand();
            pragma.CommandText = "PRAGMA busy_timeout=5000;";
            pragma.ExecuteNonQuery();
        }
        return connection;
    }

    private static DbCommand Command(DbConnection db, string sql, params (string Name, object? Value)[] args)
    {
        var cmd = db.CreateCommand();
        cmd.CommandText = sql;
        foreach (var (name, value) in args)
        {
            var p = cmd.CreateParameter();
            p.ParameterName = name;
            p.Value = value ?? DBNull.Value;
            cmd.Parameters.Add(p);
        }
        return cmd;
    }

    public void Initialize()
    {
        using var db = Open();
        using var cmd = Command(db, """
            CREATE TABLE IF NOT EXISTS skill_security_revisions (
                name TEXT NOT NULL, version TEXT NOT NULL, description TEXT NOT NULL,
                sha256 TEXT NOT NULL, staging_key TEXT NOT NULL,
                state TEXT NOT NULL, risk_score INTEGER, recommendation TEXT, report_json TEXT,
                updated_at TEXT NOT NULL, PRIMARY KEY(name, version)
            );
            CREATE INDEX IF NOT EXISTS skill_security_state_updated
                ON skill_security_revisions(state, updated_at);
            CREATE INDEX IF NOT EXISTS skill_security_approved_keyset
                ON skill_security_revisions(state,name,version);
            CREATE TABLE IF NOT EXISTS skill_security_audit (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL, version TEXT NOT NULL, sha256 TEXT NOT NULL,
                old_state TEXT NOT NULL, new_state TEXT NOT NULL,
                actor TEXT NOT NULL, reason TEXT NOT NULL, created_at TEXT NOT NULL
            );
            """.Replace("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                db is SqliteConnection ? "id INTEGER PRIMARY KEY AUTOINCREMENT"
                    : "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"));
        cmd.ExecuteNonQuery();
    }

    private static Revision Read(DbDataReader r) => new(
        r.GetString(0), r.GetString(1), r.GetString(2), r.GetString(3), r.GetString(4),
        r.GetString(5), r.IsDBNull(6) ? null : r.GetInt32(6),
        r.IsDBNull(7) ? null : r.GetString(7),
        r.IsDBNull(8) ? null : r.GetString(8), r.GetString(9));

    public Revision? Get(string name, string version)
    {
        using var db = Open();
        using var cmd = Command(db, """
            SELECT name,version,description,sha256,staging_key,state,risk_score,
                   recommendation,report_json,updated_at
            FROM skill_security_revisions WHERE name=@name AND version=@version
            """, ("name", name), ("version", version));
        using var reader = cmd.ExecuteReader();
        return reader.Read() ? Read(reader) : null;
    }

    public IReadOnlyList<Revision> List(int limit = 100)
    {
        using var db = Open();
        using var cmd = Command(db, """
            SELECT name,version,description,sha256,staging_key,state,risk_score,
                   recommendation,report_json,updated_at
            FROM skill_security_revisions ORDER BY updated_at DESC LIMIT @limit
            """, ("limit", Math.Clamp(limit, 1, 1000)));
        using var r = cmd.ExecuteReader();
        var items = new List<Revision>();
        while (r.Read()) items.Add(Read(r));
        return items;
    }

    /// <summary>
    /// One bounded, provider-side keyset page. All approved-release predicates
    /// are evaluated inside the selected metadata database before LIMIT.
    /// A cursor identifies a position, not an approval or a snapshot.
    /// </summary>
    public IReadOnlyList<SkillEntry> ReadablePage(string? afterName, string? afterVersion,
        int limit, bool approvalEnforced)
    {
        if (limit is < 1 or > 100 ||
            (afterName is null) != (afterVersion is null) ||
            (afterName is not null &&
             (!Names.Skill(afterName) || !Names.Version(afterVersion))))
            throw new ArgumentException("Invalid approved-skill keyset page.");

        var collation = settings.MetadataProvider == "postgresql" ? "\"C\"" : "BINARY";
        var orderAlias = approvalEnforced ? "r" : "s";
        var selection = approvalEnforced
            ? """
              FROM skill_security_revisions AS r
              JOIN skills AS s ON s.name = r.name AND s.version = r.version
              WHERE r.state = 'APPROVED'
              """
            : "FROM skills AS s WHERE 1=1";
        var continuation = afterName is null ? "" : $"""
             AND ({orderAlias}.name COLLATE {collation} > @afterName OR
                  ({orderAlias}.name = @afterName AND
                   {orderAlias}.version COLLATE {collation} > @afterVersion))
            """;
        var sql = $"""
            SELECT s.name,s.version,s.description,s.updated_at
            {selection}
            {continuation}
            ORDER BY {orderAlias}.name COLLATE {collation},
                     {orderAlias}.version COLLATE {collation}
            LIMIT @limit
            """;
        using var db = Open();
        using var cmd = Command(db, sql, ("limit", limit));
        if (afterName is not null)
        {
            var nameParameter = cmd.CreateParameter();
            nameParameter.ParameterName = "afterName";
            nameParameter.Value = afterName;
            cmd.Parameters.Add(nameParameter);
            var versionParameter = cmd.CreateParameter();
            versionParameter.ParameterName = "afterVersion";
            versionParameter.Value = afterVersion!;
            cmd.Parameters.Add(versionParameter);
        }
        using var reader = cmd.ExecuteReader();
        var entries = new List<SkillEntry>();
        while (reader.Read())
            entries.Add(new SkillEntry(reader.GetString(0), reader.GetString(1),
                reader.GetString(2), reader.GetString(3)));
        return entries;
    }

    /// <summary>
    /// Exact skill metadata without loading unrelated revisions.
    /// Does not prove blob integrity; callers must still check the approved digest.
    /// </summary>
    public SkillEntry? Readable(string name, string version, bool approvalEnforced)
    {
        if (!Names.Skill(name) || !Names.Version(version)) return null;
        using var db = Open();
        var selection = approvalEnforced
            ? """
              FROM skills AS s
              JOIN skill_security_revisions AS r ON r.name=s.name AND r.version=s.version
              WHERE s.name=@name AND s.version=@version AND r.state='APPROVED'
              """
            : "FROM skills AS s WHERE s.name=@name AND s.version=@version";
        using var cmd = Command(db,
            "SELECT s.name,s.version,s.description,s.updated_at " + selection,
            ("name", name), ("version", version));
        using var reader = cmd.ExecuteReader();
        return reader.Read() ? new SkillEntry(reader.GetString(0), reader.GetString(1),
            reader.GetString(2), reader.GetString(3)) : null;
    }

    public bool IsApproved(string name, string version) =>
        Get(name, version)?.State == "APPROVED";

    public bool TryStage(string name, string version, string description, string digest, string key)
    {
        using var db = Open();
        using var cmd = Command(db, """
            INSERT INTO skill_security_revisions
                (name,version,description,sha256,staging_key,state,updated_at)
            VALUES(@name,@version,@description,@digest,@key,'QUEUED',@now)
            ON CONFLICT(name,version) DO NOTHING
            """, ("name", name), ("version", version), ("description", description),
            ("digest", digest), ("key", key), ("now", DateTimeOffset.UtcNow.ToString("O")));
        return cmd.ExecuteNonQuery() == 1;
    }

    public bool SaveResult(string name, string version, string digest, string status,
        int? risk, string? recommendation, string? report)
    {
        if (status is not ("NEEDS_REVIEW" or "QUARANTINED" or "SCAN_FAILED"))
            throw new ArgumentOutOfRangeException(nameof(status));
        using var db = Open();
        using var cmd = Command(db, """
            UPDATE skill_security_revisions
            SET state=@state, risk_score=@risk, recommendation=@recommendation,
                report_json=@report,updated_at=@now
            WHERE name=@name AND version=@version AND sha256=@digest AND state='QUEUED'
            """, ("state", status), ("risk", risk), ("recommendation", recommendation),
            ("report", report), ("now", DateTimeOffset.UtcNow.ToString("O")),
            ("name", name), ("version", version), ("digest", digest));
        return cmd.ExecuteNonQuery() == 1;
    }

    public bool TryTransition(string name, string version, string digest,
        string expected, string next, string actor, string reason)
    {
        if (reason.Length is < 3 or > 512) return false;
        using var db = Open();
        using var tx = db.BeginTransaction();
        using var cmd = Command(db, """
            UPDATE skill_security_revisions SET state=@next,updated_at=@now
            WHERE name=@name AND version=@version AND sha256=@digest AND state=@expected
            """, ("next", next), ("now", DateTimeOffset.UtcNow.ToString("O")),
            ("name", name), ("version", version), ("digest", digest), ("expected", expected));
        cmd.Transaction = tx;
        if (cmd.ExecuteNonQuery() != 1) return false;
        using var audit = Command(db, """
            INSERT INTO skill_security_audit
                (name,version,sha256,old_state,new_state,actor,reason,created_at)
            VALUES(@name,@version,@digest,@previous,@next,@actor,@reason,@now)
            """, ("name", name), ("version", version), ("digest", digest),
            ("previous", expected), ("next", next), ("actor", actor),
            ("reason", reason), ("now", DateTimeOffset.UtcNow.ToString("O")));
        audit.Transaction = tx;
        audit.ExecuteNonQuery();
        tx.Commit();
        return true;
    }

    public object[] History(string name, string version)
    {
        using var db = Open();
        using var cmd = Command(db, """
            SELECT old_state,new_state,actor,reason,created_at FROM skill_security_audit
            WHERE name=@name AND version=@version ORDER BY created_at DESC LIMIT 100
            """, ("name", name), ("version", version));
        using var r = cmd.ExecuteReader();
        var records = new List<object>();
        while (r.Read())
            records.Add(new { from = r.GetString(0), to = r.GetString(1),
                actor = r.GetString(2), reason = r.GetString(3), at = r.GetString(4) });
        return [.. records];
    }
}
